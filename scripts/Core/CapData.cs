    /// <param name="Hi">Optional: von Hand gezeichnet auf dem feinen 24×24-Raster ('.' = Deckel bleibt).</param>
    /// <param name="Rim">Optional: Farbe des Blechs (z. B. Gold statt Silber).</param>
