    /// <summary>
    /// Motiv aus Textzeilen. 8×8 liegt auf der Deckelfläche (Feld 2..9); 10×10 bedruckt den ganzen
    /// Deckel bis an die Zacken (Feld 1..10), wie bei echten Marken-Kronkorken.
    /// Die vier Ecken des Rasters liegen außerhalb des Deckels und bleiben leer.
    /// </summary>
    static Motif Art(string set, string name, string face, params string[] rows)
    {
        int w = rows.Length > 0 ? rows[0].Length : 8;
        if (w != 8 && w != 10) throw new ArgumentException($"Kronkorken {name}: Zeilen müssen 8 oder 10 Zeichen haben");
        if (rows.Length > w) throw new ArgumentException($"Kronkorken {name}: {rows.Length} Zeilen statt höchstens {w}");
        int off = (12 - w) / 2;
        var px = new List<Px>();
        // Ganz bedruckt: die Deckelfarbe reicht bis an die Zacken
        if (w == 10) { px.Add(new Px(2, 1, 8, 1, face)); px.Add(new Px(1, 2, 10, 8, face)); px.Add(new Px(2, 10, 8, 1, face)); }
        for (int y = 0; y < rows.Length; y++)
        {
            var r = rows[y];
            if (r.Length != w) throw new ArgumentException($"Kronkorken {name}: Zeile {y} hat {r.Length} Zeichen statt {w}");
            for (int x = 0; x < w;)
            {
                char c = r[x];
                if (c == '.') { x++; continue; }
                if (!Ink.TryGetValue(c, out var col)) throw new ArgumentException($"Kronkorken {name}: unbekannte Farbe '{c}'");
                int s = x;
                while (x < w && r[x] == c) x++;
                px.Add(new Px(off + s, off + y, x - s, 1, col));
            }
        }
        return new Motif(set, name, face, px.ToArray());
    }

